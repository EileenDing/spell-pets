# fitted pictures -> ../../../../fit/<kind>-<item>.webp (scaled to each pet's in-game size) + ../../sprdata9.js (index)
import re, io, base64, json, os, numpy as np
from PIL import Image
from cells import SPECIAL, EVERYDAY, PAGES
ROOT = '../../..'; os.makedirs(f'{ROOT}/fit', exist_ok=True)
src = ''.join(open(f'../../{f}').read() for f in ['sprdata.js', 'sprdata7.js'])
def base(kind):
    m = re.search(r'"pet-%s":\s*"data:image/\w+;base64,([^"]+)"' % kind, src); return Image.open(io.BytesIO(base64.b64decode(m.group(1)))).convert('RGBA')
def cx_of(im):                         # body centre: median middle of the rows in the lower body
    a = np.array(im)[..., 3] > 100; H = a.shape[0]; cs = []
    for y in range(int(H * 0.55), int(H * 0.95)):
        xs = np.where(a[y])[0]
        if len(xs): cs.append((xs.min() + xs.max()) / 2)
    return float(np.median(cs)) if cs else im.width / 2
meta = {'base': {}, 'img': {}}; total = 0
for kind in PAGES:
    b = base(kind); ref = [Image.open(f'fit/{kind}-{n}.png') for n in ('bowtie', 'checkscarf', 'roundglasses')]
    s = float(np.median([b.height / r.height for r in ref[:1]] + [b.width / r.width for r in ref[:1]]))
    meta['base'][kind] = round(cx_of(b), 1)
    for n in SPECIAL + EVERYDAY:
        im = Image.open(f'fit/{kind}-{n}.png'); im = im.resize((max(1, round(im.width * s)), max(1, round(im.height * s))), Image.LANCZOS)
        p = f'{ROOT}/fit/{kind}-{n}.webp'; im.save(p, 'WEBP', quality=88, method=6, alpha_quality=100); total += os.path.getsize(p)
        meta['img'][f'{kind}-{n}'] = [im.width, im.height, round(cx_of(im), 1)]
    print(kind, round(s, 3), b.size)
open('../../sprdata9.js', 'w').write('// Fitted outfit pictures (fit/<pet>-<item>.webp), drawn by the artist for every pet. Generated by assets/v14/pack_fit.py.\nconst FIT_META = ' + json.dumps(meta) + ';\n')
print(len(meta['img']), 'images', total // 1024, 'KB')
