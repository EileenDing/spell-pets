# one picture per pet holding all 49 fitted outfits: ../../../fit/<kind>.webp ; FIT_META.img[id] = [w, h, cx, sx, sy]
import json, os, glob
from PIL import Image
from cells import SPECIAL, EVERYDAY, PAGES
ROOT = '../../..'; s = open('../../sprdata9.js').read(); meta = json.loads(s[s.index('{'):s.rindex('}') + 1]); total = 0
for kind in PAGES:
    ims = [(n, Image.open(f'{ROOT}/fit/{kind}-{n}.webp')) for n in SPECIAL + EVERYDAY]
    cols = 7; cw = max(i.width for _, i in ims) + 2; ch = max(i.height for _, i in ims) + 2; rows = (len(ims) + cols - 1) // cols
    at = Image.new('RGBA', (cw * cols, ch * rows), (0, 0, 0, 0))
    for j, (n, im) in enumerate(ims):
        x, y = (j % cols) * cw + 1, (j // cols) * ch + 1; at.paste(im, (x, y)); meta['img'][f'{kind}-{n}'] = meta['img'][f'{kind}-{n}'][:3] + [x, y]
    p = f'{ROOT}/fit/{kind}.webp'; at.save(p, 'WEBP', quality=88, method=6, alpha_quality=100); total += os.path.getsize(p)
for f in glob.glob(f'{ROOT}/fit/*-*.webp'): os.remove(f)
open('../../sprdata9.js', 'w').write('// Fitted outfit pictures: one picture per pet (fit/<pet>.webp) holding every outfit, drawn by the artist. Generated by assets/v14/pack_fit.py + atlas.py.\nconst FIT_META = ' + json.dumps(meta) + ';\n')
print(len(os.listdir(f'{ROOT}/fit')), 'files', total // 1024, 'KB')
