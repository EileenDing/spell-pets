# Packs the ten interior sets: pictures -> ../../sprdata3.js, set data -> ../../sets2.js
import base64, io, json, os, re
from PIL import Image
here = os.path.dirname(os.path.abspath(__file__)); os.chdir(here)
exec(open('cut_v4.py').read().split("if __name__")[0])
ROOM_W, ROOM_H, WALL_Y, S = 768, 512, 300, 0.78
FLOOR = {'tidal': (420, 490), 'citrus': (405, 490), 'rainy': (862, 940), 'clock': (870, 935), 'alpine': (862, 940),
         'paper': (430, 500), 'subway': (440, 500), 'music': (862, 955), 'tea': (830, 955), 'desert': (845, 955)}
WALLNAMES = {'tidal': ('Ocean Waves', 'Fish Scale Tile'), 'citrus': ('Orange Blossom', 'Terracotta Tile'), 'rainy': ('Rainy Blue Panels', 'Grey Herringbone'),
             'clock': ('Golden Gears', 'Workshop Planks'), 'alpine': ('Snowflake', 'Pine Floor'), 'paper': ('Paper Cream', 'Honey Check'),
             'subway': ('Subway Tile', 'Terrazzo'), 'music': ('Studio Foam', 'Disco Check'), 'tea': ('Shoji Screen', 'Tatami'), 'desert': ('Desert Sand', 'Clay Tile')}
def group(iid, name, place):
    n = name.lower()
    if place == 'rug': return 'rugs'
    if 'window' in n or 'porthole' in n: return 'rugs'
    if re.search(r'workbench|nightstand|rack', n): return 'tables'
    if re.search(r'\bbed\b|chair|bench|futon|pouf|cushion|nook', n): return 'beds'
    if re.search(r'lamp|lantern|light|mobile|sign|neon|rail', n): return 'lights'
    if re.search(r'tree|plant|cactus|vase|blossom pot|blossom vase', n): return 'plants'
    if place == 'wall': return 'lights'
    if re.search(r'desk|table|shelf|cabinet|dresser|counter|trunk|chest|rack|workbench|stand|keyboard|speaker|stove|basket', n): return 'tables'
    return 'cosy'
def r5(v): return int(5 * round(v / 5))
imgs, furn, walls, floors, rooms = {}, [], [], [], []
def enc(im, q=86):
    b = io.BytesIO(); im.save(b, 'WEBP', method=6, quality=q, alpha_quality=100); return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
for rk, (sheet, rb, rname, wsw, fsw, items) in ROOMS.items():
    fl, bot = FLOOR[rk]; x0, y0, x1, y1 = rb; set_items = []
    for iid, name, place, box, opt in items:
        im = Image.open(f'cut/it-{iid}.png'); imgs['it-' + iid] = enc(im)
        w, h = im.size; bx0, by0, bx1, by1 = box
        x = round((bx0 + bx1) / 2 - x0) / (x1 - x0) * ROOM_W
        if place == 'floor': y = 340 + max(0, min(1, (by1 - fl) / (bot - fl))) * 160; size = h * S
        elif place == 'rug': y = 340 + max(0, min(1, ((by0 + by1) / 2 - fl) / (bot - fl))) * 160; size = w * S
        elif place == 'ceil': y = 0; size = h * S
        else: y = 40 + max(0, min(1, (by1 - (y0 + 20)) / (fl - (y0 + 20)))) * (WALL_Y - 44); size = h * S
        grp = group(iid, name, place)
        price = max(10, r5(8 + w * h / 1500)) + (10 if grp == 'beds' and 'bed' in name.lower() else 0)
        furn.append([iid, name, grp, price, place, round(size), round(x), round(y), rk])
        set_items.append([iid, round(x), round(y)])
    for kind, sw in (('wall', 'wall'), ('floor', 'floor')):
        imgs[f'{kind}-{rk}'] = enc(Image.open(f'cut/{kind}-{rk}.png').convert('RGB'), 90)
    walls.append([rk, WALLNAMES[rk][0], 20]); floors.append([rk, WALLNAMES[rk][1], 20])
    th = Image.open(f'cut/theme-{rk}.png').convert('RGB'); th.thumbnail((520, 360), Image.LANCZOS); imgs['theme-' + rk] = enc(th, 84)
    rooms.append({'k': rk, 'name': rname, 'wall': rk, 'floor': rk, 'items': set_items})
out = os.path.join(here, '..', '..')
open(os.path.join(out, 'sprdata3.js'), 'w').write('// Interior sets, Vol. A and B (WebP data URIs)\nObject.assign(SPR_SRC, ' + json.dumps(imgs) + ');\n')
js = ['// Ten interior sets (Pet Town Interior Collection Vol. A and B). Generated by assets/v4/pack_v4.py.',
      '// furniture: key, name, group, price, place, size, x, y, set',
      'const SET_FURN = ' + json.dumps(furn) + ';',
      'const SET_WALLS = ' + json.dumps(walls) + ';', 'const SET_FLOORS = ' + json.dumps(floors) + ';',
      'const SET_ROOMS = ' + json.dumps(rooms) + ';']
open(os.path.join(out, 'sets2.js'), 'w').write('\n'.join(js) + '\n')
print(len(furn), 'items', sum(len(v) for v in imgs.values()) // 1024, 'KB')

