# New pets (frog, octopus, capybara + colour skins) and the 16 costume sets -> ../../sprdata7.js
import base64, io, json
from PIL import Image
def enc(im, q=88):
    b = io.BytesIO(); im.save(b, 'WEBP', method=6, quality=q, alpha_quality=100); return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
def fit(im, m):
    s = min(1, m / max(im.size)); return im if s == 1 else im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
spr = {}; anch = json.load(open('anchors_new.json'))
anch['capybara'].update(ex=83.2, ey=51, es=61.5, er=0, noblink=1)       # closed, happy eyes: nothing to blink
KINDS = {'frog': ['mint', 'gold', 'pond', 'plum'], 'octopus': ['peach', 'lagoon', 'berry', 'ink'], 'capybara': ['honey', 'cocoa', 'cream', 'mist']}
for kind, sks in KINDS.items():
    for nm in [kind] + [f'{kind}-{s}' for s in sks]: spr['pet-' + nm] = enc(Image.open(f'cut/g-pet-{nm}.png'), 92)
info = json.load(open('wear_info.json')); cos = {}
NAMES = {'mermaid': 'Mermaid', 'unicorn': 'Unicorn', 'ming': 'Ming Official', 'wuxia': 'Black & Red Wuxia', 'cinderella': 'Cinderella', 'snowwhite': 'Snow White', 'donut': 'Donut',
         'hunter': 'Woodland Hunter', 'jungle': 'Jungle Wildling', 'army': 'Army', 'gentleman': 'Court Gentleman', 'lady': 'Court Lady', 'pharaoh': 'Pharaoh', 'peterpan': 'Peter Pan',
         'dino': 'Dino Costume', 'octocos': 'Octopus Costume'}
PIECES = {'mermaid': 3, 'unicorn': 2, 'ming': 2, 'wuxia': 3, 'cinderella': 3, 'snowwhite': 2, 'donut': 2, 'hunter': 4, 'jungle': 3, 'army': 4, 'gentleman': 4, 'lady': 2, 'pharaoh': 3, 'peterpan': 3, 'dino': 2, 'octocos': 2}
PRICE = {2: 60, 3: 80, 4: 100}
OPEN = {'pharaoh': [0.14, 0.42, 0.86, 1.0]}
for nm, parts in info.items():
    ps = []
    for j, d in parts.items():
        k = f'cos-{nm}-{j}'; spr[k] = enc(fit(Image.open(f'wear/final-{nm}-{j}.png'), 220))
        p = {'k': k, 'layer': d['layer']}
        if d['layer'] == 'hood': p['open'] = OPEN.get(nm) or d['open']
        ps.append(p)
    spr['cosset-' + nm] = enc(fit(Image.open(f'wear/final-set-{nm}.png'), 260))
    cos[nm] = {'name': NAMES[nm], 'price': PRICE[PIECES[nm]], 'parts': ps}
open('../../sprdata7.js', 'w').write('// New pets (frog, octopus, capybara and their colour skins) and the costume sets. Generated by assets/v11/pack_v11.py.\n'
    'Object.assign(SPR_SRC, ' + json.dumps(spr) + ');\nObject.assign(PET_ANCHOR, ' + json.dumps({k: anch[k] for k in KINDS}) + ');\nconst COSTUMES = ' + json.dumps(cos) + ';\n')
print(len(spr), 'images', sum(len(v) for v in spr.values()) // 1024, 'KB')
