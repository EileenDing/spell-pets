# Packs the 14 finished set rooms and their wall/floor swatches -> ../../sprdata3.js, set data -> ../../sets2.js
import base64, io, json, os
from PIL import Image
here = os.path.dirname(os.path.abspath(__file__)); os.chdir(here)
from compose_v9 import SETS
def enc(im, q=88, mode='WEBP'):
    b = io.BytesIO(); im.save(b, 'WEBP', method=6, quality=q, alpha_quality=100); return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
WN = {'forest': ('Warm Wood', 'Honey Plank'), 'cottage': ('Cream Plaster', 'Wood Wainscot'), 'pastel': ('Pink Stripe', 'Pale Boards'), 'starry': ('Blue Star Panel', 'Medium Wood'),
      'tidal': ('Aqua Ripple', 'Blue Mosaic'), 'citrus': ('Orange Blossom', 'Terracotta Tile'), 'rainy': ('Slate Rain Stripe', 'Grey Herringbone'), 'clock': ('Brass Gear', 'Dark Walnut Board'),
      'alpine': ('Ivory Snowflake', 'Pale Timber'), 'paper': ('Origami Diagram', 'Honey Checker'), 'subway': ('Green Subway Tile', 'Speckled Terrazzo'), 'music': ('Purple Acoustic', 'Wood-Vinyl Checker'),
      'tea': ('Botanical Rice Paper', 'Tatami Grid'), 'desert': ('Peach Dune', 'Rose Adobe Tile')}
imgs, rooms, walls, floors = {}, [], [], []
for k, (name, plan) in SETS.items():
    imgs['theme-' + k] = enc(Image.open(f'rooms/{k}.png'), 86)
    imgs['wall-' + k] = enc(Image.open(f'cut/wall-{k}.png'), 90); imgs['floor-' + k] = enc(Image.open(f'cut/floor-{k}.png'), 90)
    price = int(5 * round((80 + 10 * len(plan)) / 5))
    rooms.append({'k': k, 'name': name, 'wall': k, 'floor': k, 'items': [], 'scene': 1, 'floorY': 300, 'price': price, 'pieces': len(plan)})
    walls.append([k, WN[k][0], 20]); floors.append([k, WN[k][1], 20])
out = os.path.join(here, '..', '..')
open(os.path.join(out, 'sprdata3.js'), 'w').write('// Room sets: finished rooms (1536x1024) and their walls and floors (WebP data URIs)\nObject.assign(SPR_SRC, ' + json.dumps(imgs) + ');\n')
open(os.path.join(out, 'sets2.js'), 'w').write('\n'.join([
  '// Fourteen room sets, each one finished room built from the Pet Town catalog pieces (assets/v9). Generated by assets/v9/pack_v9.py.',
  'const SET_FURN = [];', 'const SET_WALLS = ' + json.dumps(walls) + ';', 'const SET_FLOORS = ' + json.dumps(floors) + ';', 'const SET_ROOMS = ' + json.dumps(rooms) + ';']) + '\n')
print(len(rooms), sum(len(v) for v in imgs.values()) // 1024, 'KB', [(r['k'], r['price']) for r in rooms])
